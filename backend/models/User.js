const mongoose = require('mongoose');

const UserSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
    unique: true
  },
  password: {
    type: String,
    required: true
  },
  role: {
    type: String,
    default: 'Researcher' // Can be Researcher or Healthcare Worker
  }
}, { timestamps: true });

module.exports = mongoose.model('User', UserSchema);
